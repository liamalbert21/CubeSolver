#ifndef MOTOR_DEFS_H
#define MOTOR_DEFS_H

typedef enum
{
    /* PWM1 */
    MOTOR_SIDE_RED,
    MOTOR_SIDE_YELLOW,
    MOTOR_SIDE_BLUE,
    
    /* PWM2 */
    MOTOR_SIDE_ORANGE,
    MOTOR_SIDE_GREEN,
    MOTOR_SIDE_WHITE,
    
    MOTOR_NUM_SIDES
} MotorSide;

typedef enum
{
    MOTOR_CHANNEL_PWM1,
    MOTOR_CHANNEL_PWM2,
    MOTOR_NUM_PWM_CHANNELS
} MotorPWMChannel;

typedef enum
{
    MOTOR_DIR_CW,
    MOTOR_DIR_CCW
} MotorDir;

typedef struct
{
    MotorSide side;
    MotorDir dir;
} MotorConfig;

typedef struct
{
    int degrees, time_ms;
} MotorPWMConfig;

#define MOTOR_PWM1_DIR_PORT   GPIOA
#define MOTOR_PWM1_DIR_PIN    LL_GPIO_PIN_0
#define MOTOR_PWM1_DIR_PINOUT MOTOR_PWM1_DIR_PORT, MOTOR_PWM1_DIR_PIN

#define MOTOR_PWM2_DIR_PORT   GPIOA
#define MOTOR_PWM2_DIR_PIN    LL_GPIO_PIN_1
#define MOTOR_PWM2_DIR_PINOUT MOTOR_PWM2_DIR_PORT, MOTOR_PWM2_DIR_PIN

#define RED_ENABLE_PORT        GPIOB
#define RED_ENABLE_PIN         LL_GPIO_PIN_2
#define RED_ENABLE_PINOUT      RED_ENABLE_PORT, RED_ENABLE_PIN

#define ORANGE_ENABLE_PORT     GPIOB
#define ORANGE_ENABLE_PIN      LL_GPIO_PIN_1
#define ORANGE_ENABLE_PINOUT   ORANGE_ENABLE_PORT, ORANGE_ENABLE_PIN

#define YELLOW_ENABLE_PORT     GPIOB
#define YELLOW_ENABLE_PIN      LL_GPIO_PIN_15
#define YELLOW_ENABLE_PINOUT   YELLOW_ENABLE_PORT, YELLOW_ENABLE_PIN

#define GREEN_ENABLE_PORT      GPIOB
#define GREEN_ENABLE_PIN       LL_GPIO_PIN_14
#define GREEN_ENABLE_PINOUT    GREEN_ENABLE_PORT, GREEN_ENABLE_PIN

#define BLUE_ENABLE_PORT       GPIOB
#define BLUE_ENABLE_PIN        LL_GPIO_PIN_13
#define BLUE_ENABLE_PINOUT     BLUE_ENABLE_PORT, BLUE_ENABLE_PIN

#define WHITE_ENABLE_PORT      GPIOC
#define WHITE_ENABLE_PIN       LL_GPIO_PIN_4
#define WHITE_ENABLE_PINOUT    WHITE_ENABLE_PORT, WHITE_ENABLE_PIN

#endif